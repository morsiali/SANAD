export function hasKey(k: string) {
  return k in EN;
}

export function txContent(text: string, lang: Lang): string {
  if (lang !== 'ar') return text;
  return contentAr[text] ?? text;
}

function renderParam(key: string, v: string | number | Msg, lang: Lang): string {
  if (typeof v === 'number') return String(v);
  if (typeof v === 'object') return renderMsg(v, lang);
  if (v.startsWith('@')) return renderMsg({ k: v.slice(1) }, lang);
  if (key === 'role' || key === 'role2') return lang === 'ar' ? ROLE_AR[v as Role] ?? v : ROLE_LABEL[v as Role] ?? v;
  if (key === 'stage') return lang === 'ar' ? STAGE_AR[v as Stage] ?? v : STAGE_LABEL[v as Stage]?.toLowerCase() ?? v;
  if (key === 'priority' || key === 'old' || key === 'new') return lang === 'ar' ? PRIORITY_AR[v as Priority] ?? v : PRIORITY_EN[v as Priority] ?? v;
  if (key === 'category') return lang === 'ar' ? CATEGORY_AR[v as Category] ?? v : CATEGORY_LABEL[v as Category]?.toLowerCase() ?? v;
  if (key === 'effort') return renderMsg({ k: `effort_${v}` }, lang);
  return txContent(v, lang);
}

const LATIN = /[A-Za-z]/;

export function renderMsg(m: Msg | null | undefined, lang: Lang): string {
  if (!m) return '';
  if (lang === 'ar' && m.p) {
    // English keywords quoted inside Arabic sentences read badly: translate them, or use the short form.
    if (m.k === 'r_matched') {
      const hits = String(m.p.hits).split(', ').map((h) => h.replace(/[“”]/g, ''));
      const tr = hits.map((h) => (LATIN.test(h) ? contentAr[h] ?? null : h));
      if (tr.some((x) => x === null)) return renderMsg({ k: 'r_matched_short', p: { rule: m.p.rule } }, lang);
      return baseRender({ k: 'r_matched', p: { ...m.p, hits: tr.map((x) => `«${x}»`).join('، ') } }, 'ar');
    }
    if ((m.k === 'r_priority' || m.k === 'r_raised') && LATIN.test(String(m.p.signal))) return renderMsg({ k: `${m.k}_short`, p: m.p }, lang);
    if (m.k === 'r_skill') {
      const skills = String(m.p.skills).split(', ').map((x) => contentAr[x] ?? x);
      return (AR.r_skill ?? '').replace('{skills}', skills.join('، '));
    }
  }
  return baseRender(m, lang);
}

function baseRender(m: Msg, lang: Lang): string {
  const table = lang === 'ar' ? AR : EN;
  const tpl = table[m.k] ?? EN[m.k] ?? m.k;
  let out = tpl.replace(/\{(\w+)\}/g, (_, name: string) => (m.p && name in m.p ? renderParam(name, m.p[name], lang) : `{${name}}`));
  if (lang === 'en') {
    // Simple English plurals for "(s)" templates.
    const n = m.p?.n;
    out = out.replace(/(\w+)\(s\)/g, (_, w: string) => (n === 1 ? w : `${w}s`));
    out = out.replace(/(\d+) challenge\(s\)/g, '$1 challenges');
  } else {
    out = out.replace(/\(s\)/g, '');
  }
  return out;
}

